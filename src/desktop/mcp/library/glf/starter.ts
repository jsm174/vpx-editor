// Generates the script + collections for the bundled GLF starter table
// (public/templates/glfTutorialPlunger.vpx). The template's embedded script predates the
// modern CreateGlf* API, so vpx_new discards it and wires the same geometry
// (LeftFlipper/RightFlipper, swTrough1..8, Plunger + sw01 lane trigger, gi1..4)
// against the bundled modern framework instead.
//
// Conventions the modern framework imposes (verified against vpx-glf.vbs):
//   - trough is name-based: balls are created in swTrough1..tnob at Glf_Init and the
//     kick chain covers swTrough1..7, with a part named Drain as the drain entry —
//     the starter's swTrough8 plays that role, so it is aliased and its events
//     forwarded; tnob must be 7 so the chain reaches the alias.
//   - the event loop is Glf_GameTimer_Timer(); the starter's timer part is named
//     Glf_EventTimer, so its event is forwarded (and its interval set to the
//     documented -1 at init).
//   - keyboard flipper dispatch only fires s_left_flipper/s_right_flipper.
import fs from 'fs-extra';
import path from 'node:path';
import type { Collection } from '../../../../types/data.js';
import { emitBallDevice, emitFlipper } from './emit.js';
import { GLF_REQUIRED_COLLECTIONS } from './scaffold.js';

export const GLF_STARTER_TNOB = 7;

export interface StarterScriptOptions {
  /** Full text of the bundled modern vpx-glf.vbs. */
  frameworkText: string;
  /** Alphanumeric cGameName. */
  gameName: string;
}

export function buildGlfStarterScript(opts: StarterScriptOptions): string {
  const left = emitFlipper({ name: 'left', flipperPart: 'LeftFlipper' });
  const right = emitFlipper({ name: 'right', flipperPart: 'RightFlipper' });
  const plunger = emitBallDevice({
    name: 'plunger',
    ballSwitches: ['sw01'],
    ejectTimeout: 200,
    kickAngle: 0,
    kickForce: 45,
    mechanicalEject: true,
    defaultDevice: true,
  });

  const indent = (block: string) =>
    block
      .split('\n')
      .map(l => (l.length ? `    ${l}` : l))
      .join('\n');

  const game = [
    "' ============================================================================",
    `' GLF starter game (generated by vpx-editor) — framework above, game below.`,
    "' ============================================================================",
    `Const cGameName = "${opts.gameName}"`,
    'Const BallSize = 50',
    'Const BallMass = 1',
    `Const tnob = ${GLF_STARTER_TNOB}`,
    'Const lob = 0',
    'Dim tablewidth : tablewidth = Table1.width',
    'Dim tableheight : tableheight = Table1.height',
    'Dim gBOT',
    'Dim Drain : Set Drain = swTrough8',
    '',
    'Sub swTrough8_Hit : Drain_Hit : End Sub',
    'Sub swTrough8_UnHit : Drain_UnHit : End Sub',
    'Sub Glf_EventTimer_Timer : Glf_GameTimer_Timer : End Sub',
    '',
    'Sub Table1_Init',
    '    Glf_EventTimer.Interval = -1',
    '    ConfigureGlfDevices()',
    '    Glf_Init(Table1)',
    'End Sub',
    '',
    'Sub Table1_Exit',
    '    Glf_Exit()',
    'End Sub',
    '',
    'Sub Table1_KeyDown(ByVal keycode)',
    '    If keycode = PlungerKey Then Plunger.Pullback',
    '    Glf_KeyDown(keycode)',
    'End Sub',
    '',
    'Sub Table1_KeyUp(ByVal keycode)',
    '    If keycode = PlungerKey Then Plunger.Fire',
    '    Glf_KeyUp(keycode)',
    'End Sub',
    '',
    'Sub ConfigureGlfDevices()',
    indent(left.deviceConfig),
    '',
    indent(right.deviceConfig),
    '',
    indent(plunger.deviceConfig),
    'End Sub',
    '',
    left.callbacks,
    '',
    right.callbacks,
    '',
    plunger.callbacks,
  ].join('\n');

  return `${opts.frameworkText.replace(/\s*$/, '')}\n\n${game}\n`;
}

const STARTER_GLF_MEMBERS: Record<string, string[]> = {
  glf_lights: ['gi1', 'gi2', 'gi3', 'gi4'],
  glf_switches: ['sw01'],
  glf_slingshots: ['LeftSlingShot', 'RightSlingShot'],
  glf_spinners: [],
};

/** The starter's collections with the four required glf_* collections present (existing ones kept). */
export function glfStarterCollections(existing: Collection[]): Collection[] {
  const out = [...existing];
  for (const name of GLF_REQUIRED_COLLECTIONS) {
    if (out.some(c => c.name.toLowerCase() === name)) continue;
    out.push({
      name,
      items: STARTER_GLF_MEMBERS[name] ?? [],
      fire_events: false,
      stop_single_events: false,
      group_elements: false,
    });
  }
  return out;
}

export function glfStarterGameName(displayName: string): string {
  return displayName.replace(/[^A-Za-z0-9]/g, '') || 'MyTable';
}

function defaultFrameworkFile(): string {
  const candidates = [
    process.resourcesPath ? path.join(process.resourcesPath, 'glf', 'vpx-glf.vbs') : null,
    path.join(process.cwd(), 'resources', 'glf', 'vpx-glf.vbs'),
  ].filter((c): c is string => !!c);
  return candidates.find(c => fs.existsSync(c)) ?? candidates[candidates.length - 1];
}

export interface PrepareStarterOptions {
  /** Path to the bundled vpx-glf.vbs (default: the bundled resources/glf copy). */
  frameworkFile?: string;
  /** cGameName; defaults to the work folder's basename (the table name). */
  gameName?: string;
}

export async function prepareGlfStarterWorkDir(workDir: string, options: PrepareStarterOptions = {}): Promise<void> {
  const frameworkFile = options.frameworkFile ?? defaultFrameworkFile();
  const frameworkText = await fs.readFile(frameworkFile, 'utf-8');

  const collectionsPath = path.join(workDir, 'collections.json');
  let existing: Collection[] = [];
  try {
    existing = await fs.readJson(collectionsPath);
  } catch {
    existing = [];
  }
  await fs.writeFile(collectionsPath, JSON.stringify(glfStarterCollections(existing), null, 2));

  const gameName = glfStarterGameName(options.gameName ?? path.basename(workDir));
  await fs.writeFile(path.join(workDir, 'script.vbs'), buildGlfStarterScript({ frameworkText, gameName }));
}
